def build_type_chart_rows() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for attack_type in TYPE_NAMES:
        modifiers = ATTACK_MODIFIERS.get(attack_type, {})
        for defense_type in TYPE_NAMES:
            rows.append(
                {
                    "attack_type": attack_type,
                    "defense_type": defense_type,
                    "multiplier": modifiers.get(defense_type, 1.0),
                }
            )
    return rows


def main() -> None:
    rows = build_type_chart_rows()
    pprint({"type_count": len(TYPE_NAMES), "row_count": len(rows), "electric_vs_water": [row for row in rows if row["attack_type"] == "electric" and row["defense_type"] == "water"][0]})


if __name__ == "__main__":
    main()
